#!/usr/bin/env bash
# Reproducible native build/test entrypoint. Run separately per ROS and sanitizer.
set -euo pipefail
task_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
task_distro="${ROS_DISTRO:?source a supported ROS environment first}"
task_label="${1:-${task_distro}-$(uname -m)}"
task_sanitizer="${2:-none}"
task_build="$task_root/build/$task_label"
mkdir -p "$task_build"
bash "$task_root/tools/verify-submodules.sh"
cmake -S "$task_root/tests/msgs/ros2_bag_test_msgs" -B "$task_build/messages" \
    -DCMAKE_INSTALL_PREFIX="$task_build/message-install" -DPython3_EXECUTABLE=/usr/bin/python3
cmake --build "$task_build/messages" --parallel 2
cmake --install "$task_build/messages"
set +u
# Generated by the independent interface build immediately above.
# shellcheck source=/dev/null
source "$task_build/message-install/share/ros2_bag_test_msgs/local_setup.bash"
set -u
cmake -S "$task_root" -B "$task_build/main" -DCMAKE_BUILD_TYPE=Debug \
    -DPython3_EXECUTABLE=/usr/bin/python3 -DROS2_BAG_SANITIZER="$task_sanitizer"
cmake --build "$task_build/main" --parallel 2
export ROS_LOG_DIR="$task_build/ros-logs"
mkdir -p "$ROS_LOG_DIR"
export RMW_IMPLEMENTATION=rmw_fastrtps_cpp
export ROS_DOMAIN_ID="${ROS_DOMAIN_ID:-173}"
ctest --test-dir "$task_build/main" --output-on-failure
"$task_build/main/ros2_bag_recorder" --phase0-info
python3 "$task_root/tools/build-manifest.py" "$task_build/main/ros2_bag_recorder" \
    "$task_build/main/build-manifest.json" --base-image "${ROS2_BAG_BASE_IMAGE:-not-recorded}"
